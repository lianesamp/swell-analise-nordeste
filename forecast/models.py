"""
Pydantic models for the surf forecast module.

These models validate data flowing through the forecast pipeline:
API responses, tide tables, and computed surf windows.
"""

from datetime import datetime
from typing import Literal

from pydantic import BaseModel, Field, field_validator


class SwellHour(BaseModel):
    """
    One hour of swell forecast data from Open-Meteo.

    Each hour has height, direction and period.  These come from the API
    as separate arrays that we zip together with timestamps.
    """

    time: datetime
    height: float = Field(ge=0, description="Swell height in meters")
    direction: float = Field(ge=0, lt=360, description="Direction FROM, in degrees")
    period: float = Field(ge=0, description="Swell period in seconds")


class TideEvent(BaseModel):
    """
    A single high or low tide event from the Mucuripe tide table.

    The Marinha do Brasil publishes these as preamar (high) and
    baixa-mar (low) with times and heights in meters above chart datum.

    Chart datum is an arbitrary reference level set by the Marinha —
    roughly the lowest astronomical tide.  So 0.3m means 30cm above
    the lowest possible tide, and 2.8m means a high spring tide.
    """

    time: datetime
    height: float = Field(ge=0, description="Height in meters above chart datum")
    type: Literal["high", "low"]


class SurfWindow(BaseModel):
    """
    A continuous period where conditions are surfable at Iracema.

    Generated by combining swell forecast + tide data + surf rules.
    This is what the user sees in the final output.
    """

    start: datetime
    end: datetime
    rating: Literal["great", "good", "fair"]
    swell_height_avg: float = Field(ge=0, description="Average swell height during window")
    swell_period_avg: float = Field(ge=0, description="Average swell period during window")
    swell_dir_avg: float = Field(ge=0, lt=360, description="Average swell direction")
    energy_avg: float = Field(ge=0, description="Average wave energy in J/m2")
    tide_height_at_peak: float = Field(ge=0, description="Tide height at the best moment")
    tide_phase_summary: str = Field(description="Tide phases during window (e.g. 'draining > low > filling')")
    warnings: list[str] = Field(default_factory=list, description="Safety warnings")

    @field_validator("end")
    @classmethod
    def end_after_start(cls, v: datetime, info) -> datetime:
        """Ensure the window end is after its start."""
        if "start" in info.data and v <= info.data["start"]:
            raise ValueError("end must be after start")
        return v


class ForecastConfig(BaseModel):
    """
    Validated forecast configuration.

    Same pattern as PipelineConfig in doc_swell/scripts/models.py:
    wraps config.py constants into a validated Pydantic model.
    """

    spot_name: str = Field(min_length=1)
    spot_lat: float = Field(ge=-90, le=90)
    spot_lon: float = Field(ge=-180, le=180)
    offshore_lat: float = Field(ge=-90, le=90)
    offshore_lon: float = Field(ge=-180, le=180)
    swell_dir_ranges: list[tuple[float, float]]
    swell_height_min: float = Field(ge=0)
    swell_period_min: float = Field(ge=0)
    tide_max_height: float = Field(ge=0)
    forecast_days: int = Field(ge=1, le=16)
    api_url: str = Field(min_length=1)
